const { } = require("../appoinments/appoinment.service");

module.exports = {

    searchpatientName: (req, res) => {
        const body = req.body
        searchpatientName(body, (err, results) => {
            if (err) {
                return res.status(200).json({
                    success: 0,
                    message: err
                });
            }

            if (results.length == 0) {
                return res.status(200).json({
                    success: 0,
                    message: "No Record Found"
                });
            }

            return res.status(200).json({
                success: 1,
                data: results
            });
        })
    },

}